'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const read=name=>fs.readFileSync(path.join(__dirname,'..',name),'utf8');
const html=read('index.html');
const css=read('clean-seventh.css');
const stats=read('espn-live.js');
new vm.Script(stats,{filename:'espn-live.js'});
assert.ok(html.includes('clean-seventh.css?v=20261104-stats4'),'New look must have its own reversible CSS layer');
assert.ok(html.includes('espn-live.js?v=20261104-metrics4'),'Stats behavior requires a fresh asset URL');
assert.ok(html.includes('clean-sixth.css?v=20261104-weight3'),'Mobile weight sizing needs a fresh asset URL');
assert.ok(css.includes('body.shua-clean.phone-mode:has(.positions .pos.active:is('),'Phone rank controls must be visible on position pages');
assert.ok(css.includes('main>.head>#positionToggle:not([hidden])'),'Use the existing rank-toggle DOM and listeners');
assert.ok(css.includes('min-height:40px'),'Rank toggles need accessible tap targets');
assert.ok(stats.includes('id="espnColumnStatSelect"')&&!stats.includes('id="espnMetricFilters"'),'Metric categories must stay dropdown-only');
assert.ok(stats.includes('id="espnSelectedStatHead"'),'Selected statistic column needs a visible label');
assert.ok(stats.includes('class="espn-metric-track"'),'Desktop list needs quantitative bars');
assert.ok(stats.includes('statValue(p,activeStat)/maxStat'),'Bars must represent actual statistics');
assert.ok(css.includes('.espn-stat-bar-head')&&css.includes('Compared to leader')===false,'Comparison bars must be distinct from the actual values');
assert.ok(css.includes('@media(max-width:760px)')&&css.includes('espn-metric-track {display:none!important}'),'Phone rows must preserve room for player names');
for(const metric of ['targets','passTD','recTD','rushTD','receptions','rushYds','recYds'])assert.ok(stats.includes("key:'"+metric+"'"),metric+' missing from the dropdown');
console.log('PASS: mobile ROS/Pre Season controls, readable rank dropdown, and proportional Stats leaderboard.');
